/**
 * Brand tokens: the one place colors, radius and fonts are defined. Rebranding
 * a fork means editing this file and running `pnpm --filter @workspace/ui tokens`.
 *
 * Names are coss ui / shadcn semantic names. Each platform maps them to its own
 * naming through a small mapping file next to this one:
 *
 * - web (`to-web-css.ts`): 1:1. Every token becomes a CSS variable (`--primary`)
 *   plus a Tailwind `--color-primary` alias in `@theme inline`.
 * - native (`to-native-css.ts`): Uniwind reads CSS variables from `global.css`,
 *   but HeroUI Native names several roles differently (`primary` is `--accent`,
 *   `card` is `--surface`, `destructive` is `--danger`, ...). The full mapping
 *   table lives in `nativeTokenSources`; `info`, `chart-*` and `sidebar-*` are
 *   web only. A brand change never edits per-platform files by hand.
 */

