// Generates the two tables that depend on the art files. Run when `assets/interim` or
// `core/group-layers.ts` changes: `node --experimental-strip-types generate-assets.ts` from this
// folder (`--check` fails if a file would change).
//
//   core/hit-masks.generated.ts    a coarse alpha mask per layer, so a tap resolves to a group
//   native/layer-sources.generated.ts   `require(...)` per file, which Metro needs as a literal
//
// Needs ImageMagick (`magick`) on the path to read the WebP alpha channel.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { allLayerNames } from "./core/group-layers.ts";
import { GRID_HEIGHT, GRID_WIDTH } from "./core/mask.ts";

const root = dirname(fileURLToPath(import.meta.url));
const assets = join(root, "assets/interim");
const check = process.argv.includes("--check");

/** A cell counts as part of the muscle when its mean alpha is above this (of 255). */
const ALPHA_CUTOFF = 90;

const stems = [...new Set(allLayerNames())].toSorted();

function mask(stem: string) {
  const raw = execFileSync(
    "magick",
    [
      join(assets, `${stem}.webp`),
      "-alpha",
      "extract",
      "-filter",
      "box",
      "-resize",
      `${GRID_WIDTH}x${GRID_HEIGHT}!`,
      "-depth",
      "8",
      "gray:-",
    ],
    { maxBuffer: 1 << 20 },
  );
  const on = (x: number, y: number) => (raw[y * GRID_WIDTH + x] ?? 0) > ALPHA_CUTOFF;
  let x0 = GRID_WIDTH;
  let y0 = GRID_HEIGHT;
  let x1 = -1;
  let y1 = -1;
  for (let y = 0; y < GRID_HEIGHT; y++) {
    for (let x = 0; x < GRID_WIDTH; x++) {
      if (!on(x, y)) continue;
      x0 = Math.min(x0, x);
      y0 = Math.min(y0, y);
      x1 = Math.max(x1, x);
      y1 = Math.max(y1, y);
    }
  }
  if (x1 < 0) throw new Error(`${stem} has no visible pixels`);
  const w = x1 - x0 + 1;
  const h = y1 - y0 + 1;
  const bytes = new Uint8Array(Math.ceil((w * h) / 8));
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (on(x0 + x, y0 + y)) {
        const bit = y * w + x;
        bytes[bit >> 3] = (bytes[bit >> 3] ?? 0) | (1 << (bit & 7));
      }
    }
  }
  return { x0, y0, w, h, bits: Buffer.from(bytes).toString("base64") };
}

const header = "// Generated by generate-assets.ts. Do not edit.\n";
const layerImport = 'import type { LayerName } from "../core/group-layers";\n';
const files = {
  "core/hit-masks.generated.ts": `${header}import type { LayerName } from "./group-layers";
import type { LayerMask } from "./mask";

export const HIT_MASKS = ${JSON.stringify(
    Object.fromEntries(stems.map((stem) => [stem, mask(stem)])),
    null,
    2,
  )} as const satisfies Record<LayerName, LayerMask>;
`,
  "native/layer-sources.generated.ts": `${header}${layerImport}
export const LAYER_SOURCES = {
${stems.map((s) => `  ${s}: require("../assets/interim/${s}.webp"),`).join("\n")}
} satisfies Record<LayerName, number>;
`,
};

let stale = false;
for (const [path, content] of Object.entries(files)) {
  const file = join(root, path);
  if (check) {
    let current = "";
    try {
      current = readFileSync(file, "utf8");
    } catch {
      current = "";
    }
    if (current !== content) {
      console.error(`${path} is out of date`);
      stale = true;
    }
  } else {
    writeFileSync(file, content);
  }
}
if (stale) process.exit(1);
